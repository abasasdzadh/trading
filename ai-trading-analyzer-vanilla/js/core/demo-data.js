// Candle Generation — Random Walk with Trend
// ---------------------------------------------------------------------------

/**
 * Generate an array of realistic OHLCV candle data.
 *
 * The algorithm:
 *  1. Start from `basePrice` at a point in the past.
 *  2. Each candle is generated by:
 *     - Computing a random drift (slight trend bias).
 *     - Applying Gaussian-like noise scaled by volatility.
 *     - Deriving open from previous close.
 *     - Deriving high/low from the range with guaranteed structure.
 *     - Generating volume with realistic base + spikes.
 *
 * @param {string} symbol    — e.g. "BTCUSDT"
 * @param {string} timeframe — e.g. "1h", "4h", "1d"
 * @param {number} [count=500]
 * @returns {Array<{time: number, open: number, high: number, low: number, close: number, volume: number}>}
 */
export function generateDemoCandles(symbol, timeframe, count = 500) {
  const preset = DEMO_SYMBOLS[symbol.toUpperCase()];
  if (!preset) {
    console.warn(`[DemoData] Unknown symbol "${symbol}", using BTCUSDT defaults.`);
    return generateDemoCandles('BTCUSDT', timeframe, count);
  }

  const { basePrice, volatility, volume: baseVolume } = preset;
  const tfMs = TIMEFRAME_MS[timeframe] ?? 3_600_000;
  const now = Math.floor(Date.now() / 1000) * 1000; // truncate to second

  // Start `count` candles ago
  const endTime = now;
  const startTime = endTime - (count * tfMs);

  const candles = [];
  let price = basePrice * (0.85 + Math.random() * 0.15); // random starting offset

  // Trend parameters — slowly drift over the dataset
  let trend = (Math.random() - 0.5) * 0.002; // initial trend bias

  for (let i = 0; i < count; i++) {
    const time = startTime + (i * tfMs);

    // Update trend periodically (mean-reverting)
    if (i % 50 === 0) {
      trend = (Math.random() - 0.5) * 0.003;
    }

    // Generate percentage change with trend + noise
    // Use Box-Muller for Gaussian-like noise
    const u1 = Math.random();
    const u2 = Math.random();
    const gaussian = Math.sqrt(-2 * Math.log(u1 || 0.0001)) * Math.cos(2 * Math.PI * u2);
    const noise = gaussian * volatility * 0.4; // scale to ~40% of daily vol per candle
    const change = trend + noise;

    const open = price;
    const close = open * (1 + change);

    // Compute high/low — wicks extend beyond the body
    const range = Math.abs(close - open);
    const upperWick = Math.abs(gaussian) * volatility * 0.3 * open;
    const lowerWick = Math.abs(gaussian * 0.7 + (Math.random() - 0.5) * 0.5) * volatility * 0.3 * open;

    const high = Math.max(open, close) + upperWick;
    const low  = Math.min(open, close) - lowerWick;

    // Ensure structural integrity: high >= max(open,close), low <= min(open,close)
    const adjustedHigh = Math.max(high, Math.max(open, close) + 0.001 * open);
    const adjustedLow  = Math.min(low,  Math.min(open, close) - 0.001 * open);

    // Volume — base volume with occasional spikes
    const volSpike = Math.random() < 0.05 ? (2 + Math.random() * 5) : 1;
    const volTrend = 1 + Math.sin(i / 80) * 0.3; // seasonal volume pattern
    const volume = baseVolume * volSpike * volTrend * (0.7 + Math.random() * 0.6);

    candles.push({
      time,
      open:  parseFloat(open.toFixed(8)),
      high:  parseFloat(adjustedHigh.toFixed(8)),
      low:   parseFloat(adjustedLow.toFixed(8)),
      close: parseFloat(close.toFixed(8)),
      volume: parseFloat(volume.toFixed(2)),
    });

    price = close;
  }

  return candles;
}

