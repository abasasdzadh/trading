/**
 * Generate a demo watchlist — a subset of the predefined symbols.
 *
 * @returns {Array<string>}
 */
export function generateDemoWatchlist() {
  // Return a random 5–7 subset of symbols
  const shuffled = [...DEMO_SYMBOL_LIST].sort(() => Math.random() - 0.5);
  const count = 5 + Math.floor(Math.random() * 3); // 5-7
  return shuffled.slice(0, count);
}

