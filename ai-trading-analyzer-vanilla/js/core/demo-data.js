/**
 * Generate demo paper trading history.
 *
 * @param {number} [count=15]
 * @returns {Array<object>}
 */
export function generateDemoTrades(count = 15) {
  const trades = [];
  const symbols = DEMO_SYMBOL_LIST;
  const directions = [SIGNAL_DIRECTIONS.LONG, SIGNAL_DIRECTIONS.SHORT];
  const strategies = Object.values(STRATEGY_TYPES);
  const exitReasons = Object.values(TRADE_EXIT_REASON);

  const now = Date.now();

  for (let i = 0; i < count; i++) {
    const symbol = symbols[Math.floor(Math.random() * symbols.length)];
    const preset = DEMO_SYMBOLS[symbol];
    const direction = directions[Math.floor(Math.random() * directions.length)];
    const strategy = strategies[Math.floor(Math.random() * strategies.length)];

    // Entry price
    const entryOffset = (Math.random() - 0.5) * 0.05;
    const entryPrice = preset.basePrice * (1 + entryOffset);

    // Random PnL between -8% and +12%
    const pnlPercent = (Math.random() - 0.4) * 20;
    const pnlSign = direction === SIGNAL_DIRECTIONS.LONG ? 1 : -1;
    const exitPrice = entryPrice * (1 + (pnlPercent / 100) * pnlSign);

    // Quantity — random USDT amount divided by price
    const usdAmount = 100 + Math.random() * 900;
    const quantity = usdAmount / entryPrice;
    const pnl = (exitPrice - entryPrice) * quantity * (direction === SIGNAL_DIRECTIONS.LONG ? 1 : -1);

    // Determine if open or closed
    const isOpen = Math.random() < 0.2; // 20% chance still open
    const entryTime = now - ((i + 1) * 600_000) + Math.floor(Math.random() * 300_000);

    trades.push({
      id:          generateId(),
      symbol,
      direction,
      strategy,
      entryPrice:  parseFloat(entryPrice.toFixed(8)),
      exitPrice:   isOpen ? null : parseFloat(exitPrice.toFixed(8)),
      quantity:    parseFloat(quantity.toFixed(8)),
      stopLoss:    parseFloat((entryPrice * (1 - 0.025 * (direction === 'long' ? 1 : -1))).toFixed(8)),
      takeProfit:  parseFloat((entryPrice * (1 + 0.05 * (direction === 'long' ? 1 : -1))).toFixed(8)),
      status:      isOpen ? TRADE_STATUS.OPEN : TRADE_STATUS.CLOSED,
      entryTime,
      exitTime:    isOpen ? null : entryTime + Math.floor(Math.random() * 1_200_000) + 60_000,
      pnl:         isOpen ? null : parseFloat(pnl.toFixed(2)),
      pnlPercent:  isOpen ? null : parseFloat(pnlPercent.toFixed(2)),
      exitReason:  isOpen ? null : exitReasons[Math.floor(Math.random() * exitReasons.length)],
    });
  }

  // Sort by entry time descending
  trades.sort((a, b) => b.entryTime - a.entryTime);
  return trades;
}

