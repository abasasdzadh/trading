/**
 * Generate realistic demo trading signals.
 *
 * @param {number} [count=20]
 * @returns {Array<object>}
 */
export function generateDemoSignals(count = 20) {
  const signals = [];
  const symbols = DEMO_SYMBOL_LIST;
  const directions = Object.values(SIGNAL_DIRECTIONS);
  const strategies = Object.values(STRATEGY_TYPES);

  const now = Date.now();

  for (let i = 0; i < count; i++) {
    const symbol = symbols[Math.floor(Math.random() * symbols.length)];
    const preset = DEMO_SYMBOLS[symbol];
    const direction = directions[Math.floor(Math.random() * directions.length)];
    const strategy = strategies[Math.floor(Math.random() * strategies.length)];
    const score = direction === SIGNAL_DIRECTIONS.NO_TRADE
      ? Math.floor(Math.random() * 30)
      : Math.floor(30 + Math.random() * 70);
    const timeframe = TIMEFRAMES[Math.floor(Math.random() * TIMEFRAMES.length)];

    // Build a list of relevant indicators
    const indicatorList = [];
    const allIndicators = Object.values(INDICATOR_TYPES);
    const indicatorCount = 2 + Math.floor(Math.random() * 4);
    const shuffled = allIndicators.sort(() => Math.random() - 0.5);
    for (let j = 0; j < indicatorCount && j < shuffled.length; j++) {
      indicatorList.push(shuffled[j]);
    }

    // Generate price around the symbol's base
    const priceOffset = (Math.random() - 0.5) * 0.1;
    const price = preset.basePrice * (1 + priceOffset);

    signals.push({
      id:          generateId(),
      symbol,
      timeframe,
      direction,
      strategy,
      score,
      price:       parseFloat(price.toFixed(8)),
      timestamp:   now - (i * 300_000) + Math.floor(Math.random() * 60_000),
      indicators:  indicatorList,
      // Optional fields
      stopLoss:    direction === SIGNAL_DIRECTIONS.NO_TRADE ? null : parseFloat((price * (1 - 0.02 * (direction === 'long' ? 1 : -1))).toFixed(8)),
      takeProfit:  direction === SIGNAL_DIRECTIONS.NO_TRADE ? null : parseFloat((price * (1 + 0.04 * (direction === 'long' ? 1 : -1))).toFixed(8)),
      reasoning:   generateReasoning(direction, strategy, symbol),
    });
  }

  // Sort by timestamp descending (most recent first)
  signals.sort((a, b) => b.timestamp - a.timestamp);
  return signals;
}

