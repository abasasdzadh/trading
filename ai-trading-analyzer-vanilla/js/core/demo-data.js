/**
 * Generate a complete demo dataset for the application.
 * Useful for initialising the entire UI in demo mode.
 *
 * @param {object} [options]
 * @param {string} [options.defaultSymbol='BTCUSDT']
 * @param {string} [options.defaultTimeframe='1h']
 * @param {number} [options.candleCount=500]
 * @returns {object}
 */
export function generateFullDemoDataset(options = {}) {
  const {
    defaultSymbol = 'BTCUSDT',
    defaultTimeframe = '1h',
    candleCount = 500,
  } = options;

  const watchlist = generateDemoWatchlist();
  const candles = generateDemoCandles(defaultSymbol, defaultTimeframe, candleCount);
  const signals = generateDemoSignals(20);
  const trades = generateDemoTrades(15);

  return {
    candles,
    signals,
    trades,
    watchlist,
    symbol: defaultSymbol,
    timeframe: defaultTimeframe,
  };
}
